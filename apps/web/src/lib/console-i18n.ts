export type ConsoleLang = "en" | "hi";

const LANG_KEY = "manobal.console.lang";
const THEME_KEY = "manobal.console.theme";

export type ConsoleTheme = "light" | "dark";

export function readConsoleLang(): ConsoleLang {
  if (typeof window === "undefined") {
    return "en";
  }
  return window.sessionStorage.getItem(LANG_KEY) === "hi" ? "hi" : "en";
}

export function readConsoleTheme(): ConsoleTheme {
  if (typeof window === "undefined") {
    return "light";
  }
  return window.sessionStorage.getItem(THEME_KEY) === "dark" ? "dark" : "light";
}

