type Widen<T> = T extends string
  ? string
  : T extends readonly (infer Item)[]
    ? readonly Widen<Item>[]
    : T extends object
      ? { [K in keyof T]: Widen<T[K]> }
      : T;

export type ConsoleCopy = Widen<(typeof CONSOLE_COPY)["en"]>;

export function useConsoleLang(): {
  lang: ConsoleLang;
  setLang: (next: ConsoleLang) => void;
  tx: ConsoleCopy;
} {
  const [lang, setLangState] = useState<ConsoleLang>("en");

  useEffect(() => {
    setLangState(readConsoleLang());
    const sync = () => setLangState(readConsoleLang());
    window.addEventListener("manobal-console-lang", sync);
    return () => window.removeEventListener("manobal-console-lang", sync);
  }, []);

  const setLang = useCallback((next: ConsoleLang) => {
    window.sessionStorage.setItem(LANG_KEY, next);
    setLangState(next);
    window.dispatchEvent(new Event("manobal-console-lang"));
    void engineClient()
      .patchOfficerProfile({ copilot_language: next, brief_language: next })
      .catch(() => undefined);
  }, []);

  return { lang, setLang, tx: CONSOLE_COPY[lang] };
}

export function tierCaption(tx: ConsoleCopy, tier: string): string {
  if (tier === "T0") {
    return tx.tierT0;
  }
  if (tier === "T1") {
    return tx.tierT1;
  }
  if (tier === "T2") {
    return tx.tierT2;
  }
  if (tier === "T3") {
    return tx.tierT3;
  }
  if (tier === "T4") {
    return tx.tierT4;
  }
  return tier;
}

export function trajectoryCopy(tx: ConsoleCopy): {
  rising: string;
  easing: string;
  steady: string;
} {
  return { rising: tx.rising, easing: tx.easing, steady: tx.steady };
}

export function localiseDomain(tx: ConsoleCopy, value: string): string {
  const key = value.trim().toLowerCase().replace(/[\s-]+/g, "_");
  return tx.domains[key] ?? value.replace(/_/g, " ");
}

export function localiseUnit(tx: ConsoleCopy, value: string): string {
  const mapped = tx.units[value];
  if (mapped) {
    return mapped;
  }
  const stripped = value.replace(/, W-?\d+$/i, "").trim();
  const unit = tx.units[stripped];
  if (unit && stripped !== value) {
    return value.replace(stripped, unit);
  }
  return value;
}

export function localisePhrase(tx: ConsoleCopy, value: string): string {
  const exact = tx.phrases[value];
  if (exact) {
    return exact;
  }
  const unit = localiseUnit(tx, value);
  if (unit !== value) {
    return unit;
  }
  return localiseDomain(tx, value);
}

export function localiseList(tx: ConsoleCopy, values: readonly string[]): string[] {
  return values.map((value) => localisePhrase(tx, value));
}

export function persistConsoleTheme(theme: ConsoleTheme) {
  if (typeof window === "undefined") {
    return;
  }
  window.sessionStorage.setItem(THEME_KEY, theme);
}
