const HI_TO_EN = Object.fromEntries(
  Object.entries(HI).map(([english, hindi]) => [hindi, english]),
) as Record<string, string>;

const Context = createContext<{
  lang: PersonnelLang;
  p: (text: string, vars?: Record<string, string | number>) => string;
  setLang: (lang: PersonnelLang) => void;
} | null>(null);

export function normalisePersonnelLang(value?: string | null): PersonnelLang {
  const code = (value ?? "").toLowerCase();
  if (code === "hi" || code === "hindi" || code === "hi-latn" || code === "hinglish") return "hi";
  if (code === "ta" || code === "tamil") return "ta";
  return "en";
}

export function personnelText(
  lang: PersonnelLang,
  text: string,
  vars: Record<string, string | number> = {},
): string {
  let value = lang === "hi" ? (HI[text] ?? text) : lang === "en" ? (HI_TO_EN[text] ?? text) : text;
  for (const [name, replacement] of Object.entries(vars)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

export function PersonnelLanguageProvider({
  children,
  fallback,
}: {
  children: ReactNode;
  fallback?: string | undefined;
}) {
  const [lang, setLanguage] = useState<PersonnelLang>(() => {
    if (typeof window === "undefined") return "en";
    const stored = window.localStorage.getItem("manobal.language");
    return normalisePersonnelLang(stored ?? fallback);
  });

  useEffect(() => {
    const stored = window.localStorage.getItem("manobal.language");
    if (!stored && fallback) setLanguage(normalisePersonnelLang(fallback));
  }, [fallback]);

  useEffect(() => {
    const sync = () => {
      const stored = window.localStorage.getItem("manobal.language");
      if (stored) setLanguage(normalisePersonnelLang(stored));
    };
    window.addEventListener("manobal-language", sync);
    window.addEventListener("storage", sync);
    return () => {
      window.removeEventListener("manobal-language", sync);
      window.removeEventListener("storage", sync);
    };
  }, []);

  const setLang = useCallback((next: PersonnelLang) => {
    window.localStorage.setItem("manobal.language", next);
    setLanguage(next);
    window.dispatchEvent(new Event("manobal-language"));
  }, []);

  const p = useCallback(
    (text: string, vars: Record<string, string | number> = {}) =>
      personnelText(lang, text, vars),
    [lang],
  );
  const value = useMemo(() => ({ lang, p, setLang }), [lang, p, setLang]);
  return <Context.Provider value={value}>{children}</Context.Provider>;
}

export function usePersonnelI18n() {
  const value = useContext(Context);
  if (!value) {
    throw new Error("usePersonnelI18n must be used inside PersonnelLanguageProvider");
  }
  return value;
}

export function useOptionalPersonnelI18n() {
  return useContext(Context);
}
